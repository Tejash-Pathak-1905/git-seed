# --- Main Entrypoint ---
main() {
    if [ $# -eq 0 ]; then
        print_banner
        show_help
        exit 0
    fi

    # Handle status and uninstall directly
    for arg in "$@"; do
        case "$arg" in
            --help|-h)
                print_banner
                show_help
                exit 0
                ;;
            --status)
                print_banner
                show_status
                exit 0
                ;;
            --uninstall)
                print_banner
                uninstall_git_seed
                exit 0
                ;;
        esac
    done

    print_banner
    print_info "Running git-seed provisioner..."

    setup_template_directory
    setup_dispatcher_hooks

    local count=0
    for arg in "$@"; do
        case "$arg" in
            --graphify)
                install_recipe_graphify
                count=$((count + 1))
                ;;
            --secret-guard)
                install_recipe_secret_guard
                count=$((count + 1))
                ;;
            --branch-guard)
                install_recipe_branch_guard
                count=$((count + 1))
                ;;
            --large-file-guard)
                install_recipe_large_file_guard
                count=$((count + 1))
                ;;
            --conflict-guard)
                install_recipe_conflict_guard
                count=$((count + 1))
                ;;
            --all)
                install_recipe_graphify
                install_recipe_secret_guard
                install_recipe_branch_guard
                install_recipe_large_file_guard
                install_recipe_conflict_guard
                count=$((count + 5))
                ;;
            *)
                print_warn "Unrecognized option '$arg' (skipping)"
                ;;
        esac
    done

    configure_git

    echo ""
    print_success "=========================================================="
    print_success "git-seed setup completed successfully!"
    print_success "Template folder: ${TEMPLATE_DIR}"
    print_success "Recipes configured: ${count}"
    print_success "All future 'git init' and 'git clone' commands will inherit these hooks."
    print_success "=========================================================="
}

main "$@"
