  --large-file-guard    Pre-commit check: blocks files exceeding 25MB (prevents GitHub push rejections)
  --conflict-guard      Pre-commit check: prevents committing unresolved merge conflict markers (<<<<<<<)
  --all                 Install all curated recipes at once

