#!/usr/bin/env bash
# ==============================================================================
# git-seed / setup.sh
# Universal, zero-dependency Git template & hook manager.
# Provisions ~/.git-template with composable hooks, preserves default samples,
# supports curated developer recipes, and configures global init.templateDir.
#
# Supported OS: Windows (Git Bash/MSYS), macOS, Linux.
# ==============================================================================

set -euo pipefail

VERSION="1.0.0"
USER_HOME="${HOME:-$USERPROFILE}"
TEMPLATE_DIR="${USER_HOME}/.git-template"
HOOKS_DIR="${TEMPLATE_DIR}/hooks"

# --- Styling & Output Helpers ---
COLOR_RESET="\033[0m"
COLOR_BOLD="\033[1m"
COLOR_BLUE="\033[1;34m"
COLOR_GREEN="\033[1;32m"
COLOR_YELLOW="\033[1;33m"
COLOR_RED="\033[1;31m"
COLOR_CYAN="\033[1;36m"

print_banner() {
    printf "${COLOR_CYAN}${COLOR_BOLD}"
    cat << 'EOF'
        _ _                      _ 
  __ _ (_) |_      ___  ___  ___| |
 / _` || | __|____/ __|/ _ \/ _ \ |
| (_| || | ||_____\__ \  __/  __/_|
 \__, |/ |\__|    |___/\___|\___(_)
 |___/__/   Universal Git Template & Hook Manager
EOF
    printf "${COLOR_RESET}\n"
}

print_info() {
    printf "${COLOR_BLUE}[git-seed]${COLOR_RESET} %s\n" "$1"
}

print_success() {
    printf "${COLOR_GREEN}[git-seed ✓]${COLOR_RESET} %s\n" "$1"
}

print_warn() {
    printf "${COLOR_YELLOW}[git-seed ⚠️]${COLOR_RESET} %s\n" "$1"
}

print_error() {
    printf "${COLOR_RED}[git-seed ✖]${COLOR_RESET} %s\n" "$1" >&2
}

# --- Step 1: Detect Operating System & Default Git Template Directory ---
find_system_templates() {
    # 1. Probe via `git --exec-path`
    if command -v git >/dev/null 2>&1; then
        local exec_path
        exec_path="$(git --exec-path 2>/dev/null || true)"
        exec_path="${exec_path//\\//}"
        
        local candidates=(
            "${exec_path}/../share/git-core/templates"
            "${exec_path}/../../share/git-core/templates"
            "${exec_path}/templates"
        )
        for c in "${candidates[@]}"; do
            if [ -d "$c" ]; then
                echo "$c"
                return 0
            fi
        done
    fi

    # 2. Known standard paths per OS
    local os_paths=(
        "/c/Program Files/Git/mingw64/share/git-core/templates"
        "C:/Program Files/Git/mingw64/share/git-core/templates"
        "/usr/share/git-core/templates"
        "/usr/local/share/git-core/templates"
        "/opt/homebrew/share/git-core/templates"
    )
    for p in "${os_paths[@]}"; do
        if [ -d "$p" ]; then
            echo "$p"
            return 0
        fi
    done

    return 1
}

# --- Step 2: Initialize Template Directory Structure ---
setup_template_directory() {
    print_info "Ensuring template structure at: ${TEMPLATE_DIR}"
    mkdir -p "${HOOKS_DIR}"
    mkdir -p "${HOOKS_DIR}/pre-commit.d"
    mkdir -p "${HOOKS_DIR}/post-commit.d"
    mkdir -p "${HOOKS_DIR}/post-checkout.d"

    # Copy official default template samples (preserving non-destructive copying)
    local sys_tpl
    if sys_tpl="$(find_system_templates)"; then
        print_info "Found default Git system templates at: ${sys_tpl}"
        print_info "Synchronizing standard sample files into ~/.git-template..."
        cp -rn "${sys_tpl}/"* "${TEMPLATE_DIR}/" 2>/dev/null || cp -r "${sys_tpl}/"* "${TEMPLATE_DIR}/" || true
    else
        print_warn "Could not locate system template directory. Initializing clean template."
    fi
}

# --- Step 3: Setup Composable Dispatcher Hooks ---
setup_dispatcher_hooks() {
    for hook_name in pre-commit post-commit post-checkout; do
        local hook_file="${HOOKS_DIR}/${hook_name}"
        local hook_d="${HOOKS_DIR}/${hook_name}.d"

        cat << 'EOF' > "${hook_file}"
#!/usr/bin/env bash
# Composable Git hook dispatcher generated by git-seed
HOOK_NAME="$(basename "$0")"
HOOK_DIR="$(dirname "$0")/${HOOK_NAME}.d"

if [ -d "$HOOK_DIR" ]; then
    for script in "$HOOK_DIR"/*; do
        [ -e "$script" ] || continue
        if [ -x "$script" ]; then
            "$script" "$@" || exit $?
        elif [ -f "$script" ]; then
            bash "$script" "$@" || exit $?
        fi
    done
fi
exit 0
EOF
        chmod +x "${hook_file}" 2>/dev/null || true
    done
}

# --- Step 4: Curated Recipe Installers ---

install_recipe_graphify() {
    print_info "Installing recipe: --graphify"
    if command -v graphify >/dev/null 2>&1; then
        print_success "graphify binary detected on PATH."
    else
        print_warn "graphify is not currently installed on PATH."
        print_info "Hint: Run 'pip install graphifyy' (or uv tool install graphifyy) whenever you are ready."
        print_info "The hook is installed safely and will auto-activate once graphify is available."
    fi

    # post-commit
    cat << 'EOF' > "${HOOKS_DIR}/post-commit.d/10-graphify.sh"
#!/usr/bin/env bash
# [git-seed] graphify auto-rebuild post-commit hook
# Only runs if graphify is installed and graphify-out exists
if [ -d "graphify-out" ] && command -v graphify >/dev/null 2>&1; then
    # Run graph update and wiki export in background to prevent blocking git commit
    (graphify update . >/dev/null 2>&1 && graphify export wiki >/dev/null 2>&1 &) || true
fi
EOF
    chmod +x "${HOOKS_DIR}/post-commit.d/10-graphify.sh" 2>/dev/null || true

    # post-checkout
    cat << 'EOF' > "${HOOKS_DIR}/post-checkout.d/10-graphify.sh"
#!/usr/bin/env bash
# [git-seed] graphify auto-sync post-checkout hook
if [ -d "graphify-out" ] && command -v graphify >/dev/null 2>&1; then
    (graphify update . >/dev/null 2>&1 && graphify export wiki >/dev/null 2>&1 &) || true
fi
EOF
    chmod +x "${HOOKS_DIR}/post-checkout.d/10-graphify.sh" 2>/dev/null || true
    print_success "Recipe 'graphify' enabled in post-commit.d and post-checkout.d (AST graph + wiki auto-export)."

    # Optional Antigravity global optimization
    local gemini_config="${USER_HOME}/.gemini/config"
    if [ -d "${gemini_config}" ]; then
        local gemini_rules="${gemini_config}/GEMINI.md"
        if [ -f "${gemini_rules}" ] && grep -Fq "graphify-out" "${gemini_rules}" 2>/dev/null; then
            print_success "Global Antigravity rule already configured in ${gemini_rules}."
        else
            print_info "Antigravity detected! Installing global token-conservation rule..."
            cat << 'EOF' >> "${gemini_rules}"

# Global Antigravity Rules

## Codebase Exploration & Token Conservation
Whenever a repository has a `graphify-out/` folder:
1. **NEVER do blind whole-file reads or wide text searches** (e.g. `grep`, `Select-String`, or viewing 500+ lines) to explore code architecture, understand relationships, or find definitions.
2. **First step for architecture & navigation:** Read `graphify-out/wiki/index.md` (~400 tokens) or run `graphify query "<query>" --budget 1200`.
3. **Tracing flows & connections:** Run `graphify path "<SymbolA>" "<SymbolB>"` to trace dependencies or data flow.
4. **Inspecting load-bearing components:** Run `graphify explain "<Symbol>"`.
5. **Surgical reading only:** When `graphify query` returns exact file paths and line numbers, use `read_file` strictly with `StartLine` and `EndLine` for the target function or block. Do NOT read the entire file.
6. **Keep graph in sync:** Run `graphify update . && graphify export wiki` after modifying code structure.
EOF
            print_success "Global Antigravity rule configured in ${gemini_rules} (no per-repo .agents folder needed)."
        fi
    fi
}

install_recipe_secret_guard() {
    print_info "Installing recipe: --secret-guard"
    cat << 'EOF' > "${HOOKS_DIR}/pre-commit.d/05-secret-guard.sh"
#!/usr/bin/env bash
# [git-seed] Secret Guard: blocks staged commits containing private keys or obvious tokens

# High-risk token patterns
PATTERNS=(
    "-----BEGIN (RSA|OPENSSH|EC|PGP) PRIVATE KEY-----"
    "AKIA[0-9A-Z]{16}"
    "ghp_[0-9a-zA-Z]{36}"
    "gho_[0-9a-zA-Z]{36}"
    "sk-[a-zA-Z0-9]{48}"
)

FAIL=0
for pattern in "${PATTERNS[@]}"; do
    MATCH=$(git diff --cached --name-only -G"$pattern" 2>/dev/null || true)
    if [ -n "$MATCH" ]; then
        echo -e "\033[1;31m[git-seed ✖ Secret Guard]\033[0m Detected potential secret matching '$pattern' in:" >&2
        echo "$MATCH" >&2
        FAIL=1
    fi
done

if [ "$FAIL" -eq 1 ]; then
    echo -e "\033[1;33mCommit aborted! If this was intentional, commit with '--no-verify'.\033[0m" >&2
    exit 1
fi
exit 0
EOF
    chmod +x "${HOOKS_DIR}/pre-commit.d/05-secret-guard.sh" 2>/dev/null || true
    print_success "Recipe 'secret-guard' enabled in pre-commit.d."
}

install_recipe_branch_guard() {
    print_info "Installing recipe: --branch-guard"
    cat << 'EOF' > "${HOOKS_DIR}/pre-commit.d/01-branch-guard.sh"
#!/usr/bin/env bash
# [git-seed] Branch Guard: blocks direct commits to protected default branches (main/master)

BRANCH="$(git symbolic-ref --short HEAD 2>/dev/null || true)"
PROTECTED_BRANCHES=("main" "master")

for p in "${PROTECTED_BRANCHES[@]}"; do
    if [ "$BRANCH" = "$p" ]; then
        # Allow initial empty repo commits
        if git rev-parse --verify HEAD >/dev/null 2>&1; then
            echo -e "\033[1;31m[git-seed ✖ Branch Guard]\033[0m Direct commits to '$BRANCH' are protected!" >&2
            echo "Please create a feature branch: git checkout -b feature/your-change" >&2
            echo "To override this check: git commit --no-verify" >&2
            exit 1
        fi
    fi
done
exit 0
EOF
    chmod +x "${HOOKS_DIR}/pre-commit.d/01-branch-guard.sh" 2>/dev/null || true
    print_success "Recipe 'branch-guard' enabled in pre-commit.d."
}

install_recipe_large_file_guard() {
    print_info "Installing recipe: --large-file-guard"
    cat << 'EOF' > "${HOOKS_DIR}/pre-commit.d/15-large-file-guard.sh"
#!/usr/bin/env bash
# [git-seed] Large File Guard: prevents committing files exceeding 25MB (GitHub limit safety)
MAX_BYTES=26214400 # 25MB

FAIL=0
for file in $(git diff --cached --name-only --diff-filter=ACM 2>/dev/null); do
    if [ -f "$file" ]; then
        size=$(wc -c < "$file" 2>/dev/null || stat -c%s "$file" 2>/dev/null || stat -f%z "$file" 2>/dev/null || true)
        if [ -n "$size" ] && [ "$size" -gt "$MAX_BYTES" ]; then
            mb=$((size / 1048576))
            echo -e "\033[1;31m[git-seed ✖ Large File Guard]\033[0m '$file' is ${mb}MB (exceeds 25MB limit)!" >&2
            FAIL=1
        fi
    fi
done

if [ "$FAIL" -eq 1 ]; then
    echo "Large files degrade repository performance. Use Git LFS or .gitignore." >&2
    echo "To force commit anyway: git commit --no-verify" >&2
    exit 1
fi
exit 0
EOF
    chmod +x "${HOOKS_DIR}/pre-commit.d/15-large-file-guard.sh" 2>/dev/null || true
    print_success "Recipe 'large-file-guard' enabled in pre-commit.d."
}

install_recipe_conflict_guard() {
    print_info "Installing recipe: --conflict-guard"
    cat << 'EOF' > "${HOOKS_DIR}/pre-commit.d/02-conflict-guard.sh"
#!/usr/bin/env bash
# [git-seed] Conflict Guard: prevents committing unresolved merge conflict markers

FILES=$(git diff --cached --name-only 2>/dev/null || true)
FAIL=0

for file in $FILES; do
    if [ -f "$file" ]; then
        if grep -En '^(<<<<<<<|=======|>>>>>>>)' "$file" >/dev/null 2>&1; then
            echo -e "\033[1;31m[git-seed ✖ Conflict Guard]\033[0m Unresolved merge conflict markers in: $file" >&2
            grep -En '^(<<<<<<<|=======|>>>>>>>)' "$file" >&2 | head -n 5
            FAIL=1
        fi
    fi
done

if [ "$FAIL" -eq 1 ]; then
    echo "Please resolve all conflict markers before committing." >&2
    exit 1
fi
exit 0
EOF
    chmod +x "${HOOKS_DIR}/pre-commit.d/02-conflict-guard.sh" 2>/dev/null || true
    print_success "Recipe 'conflict-guard' enabled in pre-commit.d."
}

# --- Step 5: Status and Uninstall Utilities ---

show_status() {
    print_info "Inspecting git-seed configuration..."
    local current_tpl
    current_tpl="$(git config --global init.templateDir 2>/dev/null || echo '<not set>')"
    echo "  Global init.templateDir : ${current_tpl}"
    echo "  Template Location       : ${TEMPLATE_DIR}"

    if [ -d "${HOOKS_DIR}" ]; then
        echo ""
        echo "Active Installed Hook Modules:"
        local found=0
        for d in pre-commit.d post-commit.d post-checkout.d; do
            if [ -d "${HOOKS_DIR}/${d}" ]; then
                for s in "${HOOKS_DIR}/${d}"/*; do
                    if [ -f "$s" ]; then
                        echo "  - [${d}] $(basename "$s")"
                        found=1
                    fi
                done
            fi
        done
        [ "$found" -eq 0 ] && echo "  (No custom module hooks installed yet)"
    else
        echo "  (Template hooks directory does not exist)"
    fi
}

uninstall_git_seed() {
    print_info "Uninstalling git-seed global configuration..."
    git config --global --unset init.templateDir 2>/dev/null || true
    print_success "Global git config 'init.templateDir' has been unset."
    print_info "Your existing repositories are untouched. If you also want to remove ~/.git-template, run:"
    print_info "  rm -rf \"${TEMPLATE_DIR}\""
}

# --- Step 6: Configure Git Globally ---
configure_git() {
    print_info "Setting git config --global init.templateDir..."
    git config --global init.templateDir "${TEMPLATE_DIR}"
    print_success "Global init.templateDir configured to: $(git config --global init.templateDir)"
}

